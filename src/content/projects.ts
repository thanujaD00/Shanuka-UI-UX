export const projects: Project[] = publishedProjects.map((p) => ({ ...p, ...caseNotes[p.slug] }));

export const workProjects = projects.filter((p) => p.kind === "work");
export const featuredProjects = workProjects.filter((p) => p.featured);
export const archiveProjects = workProjects.filter((p) => !p.featured);
export const experiments = projects.filter((p) => p.kind === "experiment");

export function getProject(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

/** Next project in reading order (wraps around), skipping experiments for work. */
export function getNextProject(slug: string): Project {
  const pool = projects.filter((p) => p.kind === getProject(slug)?.kind);
  const i = pool.findIndex((p) => p.slug === slug);
  return pool[(i + 1) % pool.length];
}
